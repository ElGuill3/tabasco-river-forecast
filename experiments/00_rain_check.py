"""Experiment 00: does IMERG basin rainfall agree with the CONAGUA rain gauge?

The only CONAGUA climatological station available here is Boca del Cerro
(BDCTB), at the basin outlet; most of the basin is in Guatemala, where CONAGUA
has no gauges. A point gauge cannot match a 51 000 km2 basin mean day by day,
so the check is on monthly totals: seasonal agreement (correlation) and
whether the ratio between the two drifts over the years (a change in the
satellite record would show as a trend in the ratio).

    uv run python experiments/00_rain_check.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from riverforecast import conagua, data

OUT = Path("docs/results")


def main() -> None:
    gauge_file = Path("data/raw/conagua/climas/BDCTB.csv")
    gauge = conagua.parse_sih_csv(gauge_file.read_text(encoding="utf-8")).data["precip_mm"]
    imerg = data.imerg_basin_rain("BDCTB")

    days = imerg.index.intersection(gauge.dropna().index)
    both = pd.DataFrame({"gauge": gauge.loc[days], "imerg": imerg.loc[days]})
    complete = both.resample("MS").count()["gauge"] >= 25
    monthly = both.resample("MS").sum()[complete]
    yearly = monthly.groupby(monthly.index.year).sum()
    yearly = yearly[monthly.groupby(monthly.index.year).size() == 12]
    ratio = yearly["imerg"] / yearly["gauge"]
    slope = np.polyfit(ratio.index.to_numpy(), ratio.to_numpy(), 1)[0]
    early, late = ratio.loc[:2007].mean(), ratio.loc[2015:].mean()
    first, last = monthly.index.min(), monthly.index.max()
    gauge_mean, imerg_mean = monthly["gauge"].mean(), monthly["imerg"].mean()

    lines = [
        "# Experiment 00: IMERG basin rainfall against the CONAGUA gauge",
        "",
        "Generated by `experiments/00_rain_check.py`. Gauge: CONAGUA BDCTB (basin outlet);",
        "satellite: IMERG Early V07 basin mean. Months with at least 25 gauge days.",
        "",
        f"- Months compared: {len(monthly)} ({first:%Y-%m} to {last:%Y-%m})",
        f"- Monthly correlation: {monthly['gauge'].corr(monthly['imerg']):.3f}",
        f"- Mean monthly total: gauge {gauge_mean:.0f} mm, IMERG {imerg_mean:.0f} mm",
        f"- Complete years: {len(yearly)}; IMERG/gauge annual ratio "
        f"{ratio.min():.2f}-{ratio.max():.2f}",
        f"- Ratio trend: {slope:+.4f} per year; mean {early:.2f} up to 2007, {late:.2f} from 2015",
        "",
        "| Year | Gauge (mm) | IMERG basin (mm) | Ratio |",
        "| --- | --- | --- | --- |",
    ]
    for year, row in yearly.iterrows():
        lines.append(f"| {year} | {row.gauge:.0f} | {row.imerg:.0f} | {ratio[year]:.2f} |")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "00-rain-check.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:11]))


if __name__ == "__main__":
    main()
