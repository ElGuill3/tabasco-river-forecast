"""Experiment 02: quantile model on GloFAS inputs versus the GloFAS rating baseline.

Development issues only (reforecasts 2004-2016). For each lead, the model and
the rating curve are fitted and scored on the same folds of four whole years
(14-day buffer), on the same issue days. Model inputs: ``features.COLUMNS``.
The conformal variant widens q10-q90 with inner year folds of the training data.

    uv run python experiments/02_glofas_model.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from riverforecast import data, features
from riverforecast import evaluation as ev
from riverforecast.baselines import Rating
from riverforecast.model import ConformalQuantileModel, QuantileModel

CODE = "BDCTB"
OUT = Path("docs/results")
REPORTED = [
    "mae",
    "rmse",
    "pinball_q10",
    "pinball_q50",
    "pinball_q90",
    "coverage_80",
    "width_80",
    "high_water_mae",
    "detection",
    "false_alarm_ratio",
]


def out_of_fold(table: pd.DataFrame, stage: pd.Series, fit_predict) -> pd.DataFrame:
    """Out-of-fold quantiles; folds hold out whole years of target days."""
    by_valid = table.set_index("valid")
    parts = []
    for train, held in ev.year_folds(pd.DatetimeIndex(by_valid.index), 4, 14):
        q10, q50, q90 = fit_predict(by_valid.loc[train], stage.loc[train], by_valid.loc[held])
        parts.append(pd.DataFrame({"q10": q10, "q50": q50, "q90": q90}, index=held))
    return pd.concat(parts).sort_index()


def model_fit_predict(train, y, held):
    model = QuantileModel.fit(train[features.COLUMNS], y)
    return model.predict(held[features.COLUMNS])


def conformal_fit_predict(train, y, held):
    model = ConformalQuantileModel.fit(train[features.COLUMNS], y, pd.DatetimeIndex(train.index))
    return model.predict(held[features.COLUMNS])


def rating_fit_predict(train, y, held):
    import numpy as np

    rating = Rating.fit(pd.Series(np.exp(train["fc_q50"].to_numpy())), pd.Series(y.to_numpy()))
    return rating.predict(np.exp(held["fc_q50"].to_numpy()))


def main() -> None:
    stage = data.stage(CODE)
    development, _ = ev.split_days(stage.index)
    high_water = float(stage.loc[development].quantile(0.9))
    summary = data.glofas_reforecast_summary(CODE)
    reanalysis = data.glofas_reanalysis(CODE)

    rows = []
    for lead in (1, 3, 7):
        table = features.build(summary, reanalysis, lead)
        table = table[table["valid"].isin(development) & table["valid"].isin(stage.index)]
        table = table.drop_duplicates("valid")
        for name, fit_predict in (
            ("rating, GloFAS median", rating_fit_predict),
            ("quantile model, GloFAS inputs", model_fit_predict),
            ("quantile model + conformal interval", conformal_fit_predict),
        ):
            frame = out_of_fold(table, stage, fit_predict)
            observed = stage.loc[frame.index]
            scores = ev.summarize(observed, frame.q10, frame.q50, frame.q90, high_water)
            rows.append({"forecast": name, "lead_days": lead, **scores})

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "02-glofas-model-development.json").write_text(
        json.dumps(
            {"high_water_m": high_water, "features": features.COLUMNS, "rows": rows},
            indent=2,
            default=float,
        )
        + "\n"
    )
    header = ["forecast", "lead_days", "n", *REPORTED]
    lines = [
        "# Experiment 02: quantile model on GloFAS inputs (development)",
        "",
        "Generated by `experiments/02_glofas_model.py`. Reforecast issues 2004-2016,",
        "folds of four whole years (14-day buffer), same issue days for both forecasts.",
        f"High water: stage >= {high_water:.2f} m.",
        "",
        "| " + " | ".join(header) + " |",
        "| " + " | ".join("---" for _ in header) + " |",
    ]
    for row in rows:
        cells = [row["forecast"], str(row["lead_days"]), str(row["n"])]
        cells += [f"{row[k]:.3f}" for k in REPORTED]
        lines.append("| " + " | ".join(cells) + " |")
    (OUT / "02-glofas-model-development.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
