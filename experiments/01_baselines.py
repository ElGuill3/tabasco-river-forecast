"""Experiment 01: reference forecasts on the development period (1998-2016).

Every model must beat these numbers on the same days. The test period
(2017-2025) is not touched here.

Forecasts compared, for a target day t:

- climatology: stage percentiles for t's day of year (no input).
- rating, perfect GloFAS: the GloFAS reanalysis of the target period converted
  to stage. Not a forecast (it uses the future); it is the ceiling of reading
  GloFAS alone.
- rating, GloFAS reforecast at lead h: the ensemble median issued h days
  before t, converted with a curve fitted for that lead. This is what reading
  GloFAS forecasts against the gauge would give.

Evaluation: folds of four whole development years; each forecast is fitted on
the other years (minus a 14-day buffer) and scored on the held-out years.
High water is the 90th percentile of development stage.

    uv run python experiments/01_baselines.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from riverforecast import data
from riverforecast import evaluation as ev
from riverforecast.baselines import Climatology, Rating

CODE = "BDCTB"
LEAD_OF_CELL = 2  # GloFAS peaks two days early at this cell (glofas/cell.json)
OUT = Path("docs/results")


def cross_validated(days: pd.DatetimeIndex, fit_predict) -> pd.DataFrame:
    """Out-of-fold q10/q50/q90 for ``days`` from ``fit_predict(train, held)``."""
    parts = []
    for train, held in ev.year_folds(days, years_per_fold=4, buffer_days=14):
        q10, q50, q90 = fit_predict(train, held)
        parts.append(pd.DataFrame({"q10": q10, "q50": q50, "q90": q90}, index=held))
    return pd.concat(parts).sort_index()


def main() -> None:
    stage = data.stage(CODE)
    development, _ = ev.split_days(stage.index)
    stage = stage.loc[development]
    high_water = float(stage.quantile(0.9))

    reanalysis = data.glofas_reanalysis(CODE)
    shifted = reanalysis.shift(LEAD_OF_CELL, freq="D")  # discharge that reaches the gauge on t
    summary = data.glofas_reforecast_summary(CODE)

    results = []

    def record(name, lead, frame):
        observed = stage.loc[frame.index]
        row = ev.summarize(observed, frame.q10, frame.q50, frame.q90, high_water)
        results.append({"forecast": name, "lead_days": lead, **row})

    def climatology(train, held):
        return Climatology.fit(stage.loc[train]).predict(held)

    record("climatology", None, cross_validated(stage.index, climatology))

    paired = stage.index.intersection(shifted.dropna().index)

    def perfect(train, held):
        rating = Rating.fit(shifted.loc[train], stage.loc[train])
        return rating.predict(shifted.loc[held])

    record("rating, perfect GloFAS (ceiling)", None, cross_validated(paired, perfect))

    for lead in (1, 3, 7):
        rows = summary[summary.lead_days == lead].set_index("valid")
        rows = rows[~rows.index.duplicated()]
        valid = stage.index.intersection(rows.index)
        median = rows["q50"]

        def forecast(train, held, median=median):
            rating = Rating.fit(median.loc[train], stage.loc[train])
            return rating.predict(median.loc[held])

        frame = cross_validated(valid, forecast)
        record("rating, GloFAS reforecast", lead, frame)
        clim = cross_validated(stage.index, climatology).loc[frame.index]
        record("climatology, same days", lead, clim)

    table = pd.DataFrame(results)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "01-baselines-development.json").write_text(
        json.dumps({"high_water_m": high_water, "rows": results}, indent=2, default=float) + "\n"
    )
    columns = [
        "forecast",
        "lead_days",
        "n",
        "mae",
        "rmse",
        "pinball_q50",
        "coverage_80",
        "width_80",
        "high_water_n",
        "high_water_mae",
        "detection",
        "false_alarm_ratio",
    ]
    shown = table[columns].copy()
    shown["lead_days"] = shown["lead_days"].map(lambda v: "-" if pd.isna(v) else int(v))
    lines = [
        "# Experiment 01: baselines on the development period",
        "",
        "Generated by `experiments/01_baselines.py`. Development years 1998-2016, folds of",
        "four whole years with a 14-day buffer. Stage in metres. High water: stage >=",
        f"{high_water:.2f} m (90th percentile of development stage). Detection and false",
        "alarm ratio refer to the median forecast reaching that threshold.",
        "",
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
    ]
    for _, row in shown.iterrows():
        cells = [
            f"{v:.3f}"
            if isinstance(v, float) and not np.isnan(v)
            else ("-" if isinstance(v, float) else str(v))
            for v in row
        ]
        lines.append("| " + " | ".join(cells) + " |")
    (OUT / "01-baselines-development.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
