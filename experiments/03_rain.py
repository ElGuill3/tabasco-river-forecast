"""Experiment 03: does basin rainfall improve the GloFAS quantile model?

Development issues only (reforecasts 2004-2016). Both variants use the
conformal quantile model and are scored on the same folds of four whole years
(14-day buffer) and on the same issue days:

- GloFAS: ``features.COLUMNS``.
- GloFAS + rain: plus IMERG basin rainfall summed over 1-90 days ending on the
  issue day (``features.RAIN_COLUMNS``).

Rain enters the model only if it lowers the held-out error.

    uv run python experiments/03_rain.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from riverforecast import data, features
from riverforecast import evaluation as ev
from riverforecast.model import ConformalQuantileModel

CODE = "BDCTB"
OUT = Path("docs/results")
REPORTED = [
    "mae",
    "rmse",
    "pinball_q50",
    "coverage_80",
    "width_80",
    "high_water_mae",
    "detection",
    "false_alarm_ratio",
]


def out_of_fold(table: pd.DataFrame, stage: pd.Series, columns: list[str]) -> pd.DataFrame:
    by_valid = table.set_index("valid")
    parts = []
    for train, held in ev.year_folds(pd.DatetimeIndex(by_valid.index), 4, 14):
        model = ConformalQuantileModel.fit(
            by_valid.loc[train, columns], stage.loc[train], pd.DatetimeIndex(train)
        )
        q10, q50, q90 = model.predict(by_valid.loc[held, columns])
        parts.append(pd.DataFrame({"q10": q10, "q50": q50, "q90": q90}, index=held))
    return pd.concat(parts).sort_index()


def main() -> None:
    stage = data.stage(CODE)
    development, _ = ev.split_days(stage.index)
    high_water = float(stage.loc[development].quantile(0.9))
    summary = data.glofas_reforecast_summary(CODE)
    reanalysis = data.glofas_reanalysis(CODE)
    rain = data.imerg_basin_rain(CODE)

    rows = []
    for lead in (1, 3, 7):
        table = features.build(summary, reanalysis, lead, rain=rain)
        table = table[table["valid"].isin(development) & table["valid"].isin(stage.index)]
        table = table.drop_duplicates("valid")
        for name, columns in (
            ("GloFAS", features.COLUMNS),
            ("GloFAS + rain", features.COLUMNS + features.RAIN_COLUMNS),
        ):
            frame = out_of_fold(table, stage, columns)
            scores = ev.summarize(
                stage.loc[frame.index], frame.q10, frame.q50, frame.q90, high_water
            )
            rows.append({"inputs": name, "lead_days": lead, **scores})

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "03-rain-development.json").write_text(
        json.dumps({"high_water_m": high_water, "rows": rows}, indent=2, default=float) + "\n"
    )
    header = ["inputs", "lead_days", "n", *REPORTED]
    lines = [
        "# Experiment 03: basin rainfall as model input (development)",
        "",
        "Generated by `experiments/03_rain.py`. Conformal quantile model, reforecast issues",
        "2004-2016, folds of four whole years (14-day buffer), same issue days for both.",
        f"High water: stage >= {high_water:.2f} m.",
        "",
        "| " + " | ".join(header) + " |",
        "| " + " | ".join("---" for _ in header) + " |",
    ]
    for row in rows:
        cells = [row["inputs"], str(row["lead_days"]), str(row["n"])]
        cells += [f"{row[k]:.3f}" for k in REPORTED]
        lines.append("| " + " | ".join(cells) + " |")
    (OUT / "03-rain-development.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
