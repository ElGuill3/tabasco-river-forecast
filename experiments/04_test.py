"""Experiment 04: the one-time test of the frozen model on the test years.

Frozen model (decided on development data only, experiments 01-03): conformal
quantile model on GloFAS inputs (``features.COLUMNS``), no rainfall. It is
fitted once on every development issue (2004-2016) and scored on test issues
whose target day is 2017 or later:

- leads 3 and 7 days: reforecasts up to 2019;
- lead 1 day: reforecasts up to 2023 (the 2020-2023 issues are lead 1 only).

References, fitted on the same development data: day-of-year climatology and
the GloFAS rating curve. Run once; rerunning it must not change any decision.

    uv run python experiments/04_test.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from riverforecast import data, features
from riverforecast import evaluation as ev
from riverforecast.baselines import Climatology, Rating
from riverforecast.model import ConformalQuantileModel

CODE = "BDCTB"
OUT = Path("docs/results")
REPORTED = [
    "mae",
    "rmse",
    "pinball_q50",
    "coverage_80",
    "width_80",
    "high_water_n",
    "high_water_mae",
    "detection",
    "false_alarm_ratio",
]


def main() -> None:
    stage = data.stage(CODE)
    development, test = ev.split_days(stage.index)
    high_water = float(stage.loc[development].quantile(0.9))
    summary = data.glofas_reforecast_summary(CODE)
    reanalysis = data.glofas_reanalysis(CODE)
    climatology = Climatology.fit(stage.loc[development])

    rows, yearly = [], []
    for lead in (1, 3, 7):
        table = features.build(summary, reanalysis, lead).drop_duplicates("valid")
        table = table[table["valid"].isin(stage.index)].set_index("valid")
        train = table[table.index.isin(development)]
        held = table[table.index.isin(test)]
        observed = stage.loc[held.index]

        model = ConformalQuantileModel.fit(
            train[features.COLUMNS], stage.loc[train.index], pd.DatetimeIndex(train.index)
        )
        rating = Rating.fit(np.exp(train["fc_q50"]), stage.loc[train.index])
        forecasts = {
            "climatology": climatology.predict(pd.DatetimeIndex(held.index)),
            "GloFAS rating": rating.predict(np.exp(held["fc_q50"].to_numpy())),
            "model": model.predict(held[features.COLUMNS]),
        }
        for name, (q10, q50, q90) in forecasts.items():
            scores = ev.summarize(observed, q10, q50, q90, high_water)
            rows.append(
                {
                    "forecast": name,
                    "lead_days": lead,
                    "period": f"{held.index.min():%Y-%m-%d}..{held.index.max():%Y-%m-%d}",
                    **scores,
                }
            )
            errors = pd.Series(np.abs(q50 - observed.to_numpy()), index=held.index)
            for year, value in errors.groupby(errors.index.year).mean().items():
                yearly.append(
                    {"forecast": name, "lead_days": lead, "year": int(year), "mae": float(value)}
                )

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "04-test.json").write_text(
        json.dumps(
            {"high_water_m": high_water, "rows": rows, "yearly_mae": yearly},
            indent=2,
            default=float,
        )
        + "\n"
    )
    header = ["forecast", "lead_days", "period", "n", *REPORTED]
    lines = [
        "# Experiment 04: one-time test of the frozen model",
        "",
        "Generated by `experiments/04_test.py`. Fitted on development issues 2004-2016;",
        "scored on target days from 2017 (reforecasts: to 2019 at 3 and 7 days, to 2023",
        f"at 1 day). High water: stage >= {high_water:.2f} m.",
        "",
        "| " + " | ".join(header) + " |",
        "| " + " | ".join("---" for _ in header) + " |",
    ]
    for row in rows:
        cells = [row["forecast"], str(row["lead_days"]), row["period"], str(row["n"])]
        cells += [f"{row[k]:.3f}" if isinstance(row[k], float) else str(row[k]) for k in REPORTED]
        lines.append("| " + " | ".join(cells) + " |")
    by_year = pd.DataFrame(yearly).pivot_table(
        index="year", columns=["lead_days", "forecast"], values="mae"
    )
    lines += ["", "## MAE by year (m)", "", by_year.round(3).to_markdown()]
    (OUT / "04-test.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
